# A verse recited alone (repeated, followed by a silence to say it again, or ended by the sleep timer)
# must stop before the next verse is heard. Its endMs is where the next verse starts, often less than
# 0.1 s before that verse's first sound: the player checks its position only now and then, and the
# audio already queued in the phone, or in Bluetooth headphones, plays on after it stops. `stops`
# writes a stopMs inside the pause between the two verses, measured on the recording itself.
STOP_SAMPLE_RATE = 16000  # keeps the hiss of the fricatives some verses start with
STOP_FRAME_MS = 10
# Rumble under the voice's lowest notes, e.g. from the recording room, is not sound of the recitation.
STOP_HIGHPASS_HZ = 60
# Zero samples, e.g. at a file's trimmed edges, say nothing about the noise of the recording.
DIGITAL_SILENCE_DB = -90.0
# A frame is silent below the recording's noise floor plus half the way to its speech level,
# and never less than 6 or more than 12 dB above the floor.
QUIET_OVER_FLOOR_DB = (6.0, 12.0)
# A click or a lip noise this short, with this much silence on each side, does not end a pause. A
# verse's last sound fading in and out around the threshold has shorter silences between: still sound.
STOP_BLIP_MS = 50
STOP_BLIP_QUIET_MS = 50
# A silence this short between two sounds, e.g. a flicker as a sound starts or fades, is sound.
STOP_FLICKER_MS = 20
# Shorter silences are dips within joined words, not a pause between verses.
MIN_PAUSE_MS = 150
# How far a boundary may lie inside the next verse's first sound: aligners sometimes start a verse late.
# As far the other way, the verse's own last sound may run past it, before a pause at least this long:
# a shorter silence there may be the closure of a consonant in the next verse's first word.
LATE_BOUNDARY_MS = 300
EARLY_END_PAUSE_MS = 300
# Farther, after a pause this long, which only ends verses: a timing source that started the next verse late.
CLEAN_PAUSE_MS = 500
VERY_LATE_BOUNDARY_MS = 600
# A verse start this far inside a sound that follows such a pause and runs on into the verse cuts its first word.
LATE_START_MS = 100
# Least time from a stop to the next verse's first sound. On a phone's speaker, about 50 ms more of
# the recording is heard after the stop point (Pixel 6, 2026-10-26): its mixer runs 60 ms ahead of
# what is heard. The verse's own fading sound and its joining vowel give way to it.
STOP_MIN_LEAD_MS = 120
# Time wanted from a stop to the next verse's first sound, 200 ms of it at 1.5x speed, for Bluetooth
# headphones. A long pause is cut in its middle, which keeps some of the reciter's silence before the
# repetition starts.
STOP_LEAD_MS = 300
# The verse's own sound has died away this long before its stop, in a pause too short for the lead.
STOP_TAIL_MS = 60
# Pauses are looked for this far on either side of a boundary.
PAUSE_SEARCH_MS = 4000


class LayoutError(Exception):
    pass


@dataclass(frozen=True)
class Asset:
    pack: str
    path: str  # asset path inside the pack, e.g. quran/audio/hosary/001.mp3
    bytes: int
    sha256: str
    origin: str = '-'
    delivery: str = PLAY


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1 << 20), b''):
            digest.update(block)
    return digest.hexdigest()


def group_surahs(sizes: list[int], target: int = TARGET_PACK_BYTES, limit: int = MAX_PACK_BYTES) -> list[list[int]]:
    """Consecutive surah numbers per pack, starting a new pack once [target] would be exceeded."""
    packs: list[list[int]] = []
    current: list[int] = []
    total = 0
    for number, size in enumerate(sizes, start=1):
        if size >= limit:
            raise LayoutError(f'Surah {number} alone is {size / MB:.0f} MB, over the {limit / MB:.0f} MB pack limit')
        if current and total + size > target:
            packs.append(current)
            current, total = [], 0
        current.append(number)
        total += size
    if current:
        packs.append(current)
    return packs


def split_surahs(sizes: list[int], count: int, limit: int = MAX_PACK_BYTES) -> list[list[int]]:
    """At most [count] packs of consecutive surahs, as even as can be: the largest is as small as possible."""
    low, high = max(sizes), sum(sizes)
    while low < high:
        middle = (low + high) // 2
        if len(group_surahs(sizes, middle, limit)) <= count:
            high = middle
        else:
            low = middle + 1
    return group_surahs(sizes, low, limit)


def assign_deliveries(reciters: list[str], previous: dict[str, str]) -> dict[str, str]:
    """Google Play for the first PLAY_RECITERS reciters laid out, the Worker for the rest.

    Reciters new to this layout fill the free Play places in [reciters] order (their folder names).

    A reciter keeps what an earlier layout gave it: moving one would rename its packs and make
    everyone who downloaded it download it again.
    """
    kept = {reciter: previous[reciter] for reciter in reciters if reciter in previous}
    free = PLAY_RECITERS - list(kept.values()).count(PLAY)
    deliveries = {}
    for reciter in reciters:
        if reciter in kept:
            deliveries[reciter] = kept[reciter]
        elif free > 0:
            deliveries[reciter] = PLAY
            free -= 1
        else:
            deliveries[reciter] = CDN
    return deliveries


# Layer III bitrates by header index: MPEG-1, then MPEG-2 and 2.5 (the low sample rates of 8 to 24 kHz).
MPEG1_LAYER3_KBPS = (0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320)
MPEG2_LAYER3_KBPS = (0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160)


def mp3_format(path: Path) -> tuple[int, bool, bool] | None:
    """(kbps, mono, constant bitrate) from an MPEG Layer III file's first frame; None for anything else."""
    with path.open('rb') as stream:
        tag = stream.read(10)
        if len(tag) == 10 and tag[:3] == b'ID3':
            size = (tag[6] & 0x7f) << 21 | (tag[7] & 0x7f) << 14 | (tag[8] & 0x7f) << 7 | tag[9] & 0x7f
            stream.seek(10 + size + (10 if tag[5] & 0x10 else 0))
        else:
            stream.seek(0)
        data = stream.read(8192)
    for i in range(len(data) - 3):
        # Frame sync, then a known MPEG version, Layer III, a valid bitrate and sample rate.
        if data[i] != 0xFF or data[i + 1] & 0xE0 != 0xE0:
            continue
        version, layer = (data[i + 1] >> 3) & 3, (data[i + 1] >> 1) & 3
        bitrate, rate = data[i + 2] >> 4, (data[i + 2] >> 2) & 3
        if version == 1 or layer != 1 or not 0 < bitrate < 15 or rate == 3:
            continue
        # Encoders announce a variable bitrate in a Xing or VBRI header inside the first frame.
        first_frame = data[i:i + 200]
        table = MPEG1_LAYER3_KBPS if version == 3 else MPEG2_LAYER3_KBPS
        return table[bitrate], data[i + 3] >> 6 == 3, b'Xing' not in first_frame and b'VBRI' not in first_frame
    return None


def has_seek_header(path: Path) -> bool:
    """Whether the first frame is a Xing, Info or VBRI header rather than audio.

    Android's MediaPlayer seeks by the header's table, which places a position only to the
    nearest 1/256 of the file: tens of seconds off in a long surah. Without it, it seeks a
    constant-bitrate file exactly.
    """
    data = path.read_bytes()[:16384]
    start = 10 + ((data[6] & 0x7f) << 21 | (data[7] & 0x7f) << 14 | (data[8] & 0x7f) << 7 | data[9] & 0x7f)         if data[:3] == b'ID3' else 0
    return any(tag in data[start:start + 400] for tag in (b'Xing', b'Info', b'VBRI'))


def is_recitation_format(path: Path) -> bool:
    return mp3_format(path) == (AUDIO_KBPS, True, True) and not has_seek_header(path)


def check_recitation_format(path: Path) -> None:
    if is_recitation_format(path):
        return
    found = mp3_format(path)
    if found == (AUDIO_KBPS, True, True):
        described = f'{AUDIO_KBPS} kbps mono with a Xing/Info header, by which Android seeks to the nearest 1/256 of the file'
    elif found is None:
        described = 'not an MPEG Layer III file'
    else:
        described = f"{found[0]} kbps {'mono' if found[1] else 'stereo'}{'' if found[2] else ' at a variable bitrate'}"
    raise LayoutError(f'{path} is {described}; recitations are {AUDIO_KBPS} kbps mono at a constant bitrate, '
                      f'with no Xing/Info header. Convert them first: quran_assets.py convert --from-dir <originals> --to <folder>')


def safe_member(name: str) -> str:
    """Rejects archive member names that could escape the extraction folder."""
    path = PurePosixPath(name)
    if not name or name.startswith('/') or '\\' in name or path.is_absolute() or '..' in path.parts or ':' in name:
        raise LayoutError(f'Unsafe archive entry: {name!r}')
    return str(path)


try:
    # libdeflate's bindings (pip install deflate): its level 12 deflates the book's fonts about 4% smaller than zlib,
    # and any inflater reads it. Without them, entries are deflated by zlib as before.
    import deflate as libdeflate
except ImportError:
    libdeflate = None


class LibDeflateEntry:
    """A zip entry's compressor: the whole file deflated at once by libdeflate at level 12 (a raw deflate stream, as
    zip wants it)."""
    def __init__(self):
        self.parts = []

    def compress(self, data):
        self.parts.append(bytes(data))
        return b''

    def flush(self):
        return libdeflate.deflate_compress(b''.join(self.parts), 12)


def build_archive(files: list[tuple[str, Path]], out: Path) -> str:
    """Writes a zip with sorted entries and fixed metadata, stored (uncompressed) but for the COMPRESSED kinds (by
    libdeflate where its bindings are installed); returns its sha256."""
    out.parent.mkdir(parents=True, exist_ok=True)
    temporary = out.with_suffix(out.suffix + '.tmp')
    with zipfile.ZipFile(temporary, 'w', compression=zipfile.ZIP_STORED, allowZip64=True) as archive:
        for name, source in sorted(files):
            info = zipfile.ZipInfo(safe_member(name), date_time=ZIP_EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED if PurePosixPath(name).suffix in COMPRESSED else zipfile.ZIP_STORED
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            info.file_size = source.stat().st_size
            with source.open('rb') as src, archive.open(info, 'w') as dst:
                if libdeflate is not None and info.compress_type == zipfile.ZIP_DEFLATED:
                    dst._compressor = LibDeflateEntry()     # zipfile still computes the CRC and the sizes itself
                shutil.copyfileobj(src, dst, 1 << 20)
    temporary.replace(out)
    return sha256_of(out)


def extract_archive(archive: Path, destination: Path, expected: dict[str, int]) -> None:
    """Extracts exactly the [expected] files (path -> size) into [destination], replacing it."""
    staging = destination.with_name(destination.name + '.tmp')
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    with zipfile.ZipFile(archive) as zipped:
        names = [safe_member(info.filename) for info in zipped.infolist()]
        if sorted(names) != sorted(expected):
            raise LayoutError(f'{archive.name} does not hold the files the layout lists')
        for info in zipped.infolist():
            if info.file_size != expected[info.filename]:
                raise LayoutError(f'{info.filename} in {archive.name} has the wrong size')
            target = staging / info.filename
            target.parent.mkdir(parents=True, exist_ok=True)
            with zipped.open(info) as src, target.open('wb') as dst:
                shutil.copyfileobj(src, dst, 1 << 20)
    if destination.exists():
        shutil.rmtree(destination)
    staging.replace(destination)


# ── Committed layout ──────────────────────────────────────────────────────────

def read_manifest(path: Path | None = None) -> list[Asset]:
    path = path or MANIFEST
    if not path.exists():
        raise LayoutError(f'{path.relative_to(REPO)} is missing; run layout first')
    rows = []
    for line in path.read_text(encoding='utf-8').splitlines():
        if not line or line.startswith('#') or line.startswith('pack\t'):
            continue
        pack, asset_path, size, digest, origin, *delivery = line.split('\t')
        rows.append(Asset(pack, asset_path, int(size), digest, origin, *delivery))
    return rows


def write_manifest(assets: list[Asset], path: Path | None = None) -> None:
    path = path or MANIFEST
    path.parent.mkdir(parents=True, exist_ok=True)
    # origin: the recording a recitation was converted from. delivery: play packs are also
    # Play Asset Delivery modules; cdn packs come from the quran-cdn Worker alone.
    lines = ['# Quran media packs. Generated by scripts/quran_assets.py layout; do not edit by hand.',
             'pack\tpath\tbytes\tsha256\torigin\tdelivery']
    lines += [f'{a.pack}\t{a.path}\t{a.bytes}\t{a.sha256}\t{a.origin}\t{a.delivery}' for a in assets]
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def read_layout(path: Path | None = None) -> dict:
    path = path or LAYOUT_JSON
    if not path.exists():
        raise LayoutError(f'{path.relative_to(REPO)} is missing; run layout first')
    return json.loads(path.read_text(encoding='utf-8'))


def archive_url(layout: dict, pack: dict) -> str:
    return layout['cdn'].rstrip('/') + '/' + pack['archive']['key']


def delivery_of(pack: dict) -> str:
    return pack.get('delivery', PLAY)


def previous_deliveries() -> dict[str, str]:
    """Each reciter's delivery in the layout being replaced; empty for the first layout."""
    if not LAYOUT_JSON.exists():
        return {}
    return {pack['reciterId']: delivery_of(pack) for pack in read_layout()['packs'] if pack['kind'] == 'audio'}


def recitations() -> list[dict]:
    """Each reciter's timings.json: reciterId and the asset path of every surah."""
    found = []
    for timings in sorted(TIMINGS_DIR.glob('*/timings.json')):
        data = json.loads(timings.read_text(encoding='utf-8'))
        paths = [surah['assetPath'] for surah in sorted(data['surahs'], key=lambda s: s['number'])]
        if len(paths) != 114:
            raise LayoutError(f'{timings} lists {len(paths)} surahs, not 114')
        found.append({'reciterId': data['reciterId'], 'folder': timings.parent.name, 'paths': paths})
    if not found:
        raise LayoutError(f'No timings.json under {TIMINGS_DIR.relative_to(REPO)}; commit it first')
    return found


def page_paths() -> list[str]:
    """The page scans' asset paths, in page order."""
    if not PAGES_JSON.exists():
        raise LayoutError(f'{PAGES_JSON.relative_to(REPO)} is missing; commit it first')
    pages = json.loads(PAGES_JSON.read_text(encoding='utf-8'))['pages']
    return [f"quran/pages/{page['file']}" for page in sorted(pages, key=lambda page: page['n'])]


def book_files(folder: Path) -> tuple[list[tuple[str, Path]], int]:
    """The book in folder/quran/book, as the book build's book_pack.py writes it: plates.json, the fonts it names
    (beside it, where the app reads them) and the page layouts pages/page_NNN.bin from page 1 with no gap. Returns
    (asset path, file) for each, and the number of pages the book sets."""
    root = folder / 'quran' / 'book'
    plates = root / 'plates.json'
    if not plates.is_file():
        raise LayoutError(f'{plates} is missing: --book takes the folder book_pack.py wrote')
    files = [('quran/book/plates.json', plates)]
    for name in json.loads(plates.read_text(encoding='utf-8'))['fonts']:
        font = root / name
        if PurePosixPath(name).name != name or not font.is_file():
            raise LayoutError(f'The book names a font {name!r} that is not beside its plates.json')
        files.append((f'quran/book/{name}', font))
    pages = sorted((root / 'pages').glob('page_*.bin'))
    numbers = [int(page.stem.split('_')[1]) for page in pages]
    if not numbers or numbers != list(range(1, len(numbers) + 1)):
        raise LayoutError("The book's page layouts must run from pages/page_001.bin with no gap")
    files += [(f'quran/book/pages/{page.name}', page) for page in pages]
    return files, len(numbers)


class LocalFiles:
    """Finds media by file name in folders and zip files (zips are extracted to a temp folder).

    Reciters share file names (001.mp3 …): when several files have the name, the one in a folder
    named like the asset's (quran/audio/hosary/001.mp3 → …/hosary/001.mp3) is used.
    """

    def __init__(self, sources: list[Path]):
        self.by_name: dict[str, list[Path]] = {}
        self.temp = tempfile.TemporaryDirectory(prefix='quran-assets-')
        for source in sources:
            if source.is_file() and source.suffix.lower() == '.zip':
                folder = Path(self.temp.name) / source.stem
                with zipfile.ZipFile(source) as zipped:
                    for info in zipped.infolist():
                        if info.is_dir():
                            continue
                        target = folder / safe_member(info.filename)
                        target.parent.mkdir(parents=True, exist_ok=True)
                        with zipped.open(info) as src, target.open('wb') as dst:
                            shutil.copyfileobj(src, dst, 1 << 20)
                source = folder
            if not source.is_dir():
                raise LayoutError(f'{source} is neither a folder nor a zip file')
            for file in source.rglob('*'):
                if file.is_file():
                    found = self.by_name.setdefault(file.name, [])
                    if all(file.resolve() != known.resolve() for known in found):
                        found.append(file)

    def find(self, asset_path: str) -> Path:
        path = PurePosixPath(asset_path)
        candidates = self.by_name.get(path.name, [])
        if not candidates:
            raise LayoutError(f'No local file named {path.name} (for {asset_path})')
        if len(candidates) == 1:
            return candidates[0]
        in_folder = [c for c in candidates if c.parent.name == path.parent.name]
        if len(in_folder) != 1:
            raise LayoutError(f'{len(candidates)} local files are named {path.name}: put each reciter\'s files '
                              f'in a folder named after it ({path.parent.name}/ for {asset_path})')
        return in_folder[0]

    def close(self) -> None:
        self.temp.cleanup()


# ── Commands ──────────────────────────────────────────────────────────────────

def command_layout(args: argparse.Namespace) -> None:
    files = LocalFiles([Path(p) for p in args.from_dir])
    try:
        assets: list[Asset] = []
        packs: list[dict] = []
        sources: dict[str, Path] = {}

        def add_pack(name: str, kind: str, paths: list[str], extra: dict, origin_of, known: dict | None = None) -> None:
            entries = []
            for asset_path in paths:
                source = (known or {}).get(asset_path) or files.find(asset_path)
                sources[asset_path] = source
                size = source.stat().st_size
                assets.append(Asset(name, asset_path, size, sha256_of(source), origin_of(asset_path), extra['delivery']))
                entries.append({'path': asset_path, 'bytes': size})
            packs.append({'name': name, 'kind': kind, **extra, 'bytes': sum(e['bytes'] for e in entries), 'files': entries})

        previous = read_layout() if LAYOUT_JSON.exists() else None
        pages = page_paths()
        if args.book:
            book, sets = book_files(Path(args.book))
            if sets != len(pages):
                raise LayoutError(f'The book sets {sets} pages; pages.json has {len(pages)}')
            # The book takes the scans' place: the reader downloads it alone.
            add_pack(BOOK_PACK, 'book', [path for path, _ in book], {'delivery': PLAY}, lambda _: '-', dict(book))
        elif previous and any(pack['kind'] == 'book' for pack in previous['packs']):
            raise LayoutError('The layout holds the book: give --book (the folder book_pack.py wrote), or the reader loses it')
        else:
            add_pack(PAGES_PACK, 'pages', pages, {'delivery': PLAY}, lambda _: '-')
        found = recitations()
        deliveries = assign_deliveries([r['reciterId'] for r in found], previous_deliveries())
        for recitation in found:
            folder = recitation['folder']
            if not PACK_NAME.fullmatch(folder):
                raise LayoutError(f'Reciter folder {folder!r} must be lowercase letters, digits and underscores')
            delivery = deliveries[recitation['reciterId']]
            pattern = ORIGINS.get(folder)
            recordings = [files.find(p) for p in recitation['paths']]
            for recording in recordings:
                check_recitation_format(recording)
            sizes = [recording.stat().st_size for recording in recordings]
            if delivery == PLAY:
                groups = split_surahs(sizes, PLAY_PACKS_PER_RECITER)
            else:
                groups = group_surahs(sizes, int(args.target_mb * MB))
            for index, surahs in enumerate(groups, start=1):
                add_pack(f'quran_{folder}_{index:02d}', 'audio',
                         [recitation['paths'][n - 1] for n in surahs],
                         {'delivery': delivery, 'reciterId': recitation['reciterId'], 'surahs': [surahs[0], surahs[-1]]},
                         lambda p: pattern.format(name=PurePosixPath(p).name) if pattern else '-')
            print(f"  {recitation['reciterId']}: {'Google Play and the Worker' if delivery == PLAY else 'the Worker only'}, "
                  f"{len(groups)} pack{'' if len(groups) == 1 else 's'}, {sum(sizes) / MB:.0f} MB")
        play_packs = [p['name'] for p in packs if p['delivery'] == PLAY]
        if len(play_packs) > MAX_PLAY_PACKS:
            raise LayoutError(f'{len(play_packs)} Play packs exceed the {MAX_PLAY_PACKS}-pack limit of an app bundle')

        BUILD.mkdir(parents=True, exist_ok=True)
        # A pack whose files have not changed keeps the archive the CDN already serves (a deflated zip need not come
        # out byte for byte the same from another zlib).
        old_packs = {pack['name']: pack for pack in previous['packs']} if previous else {}
        old_hashes = {(a.pack, a.path): a.sha256 for a in read_manifest()} if previous and MANIFEST.exists() else {}
        new_hashes = {(a.pack, a.path): a.sha256 for a in assets}
        for pack in packs:
            if pack['delivery'] == PLAY and pack['bytes'] >= MAX_PACK_BYTES:
                print(f"! {pack['name']} is {pack['bytes'] / MB:.0f} MB: Play asks before using mobile data", file=sys.stderr)
            old = old_packs.get(pack['name'])
            if old and old['files'] == pack['files'] and all(
                    old_hashes.get((pack['name'], f['path'])) == new_hashes[(pack['name'], f['path'])] for f in pack['files']):
                kept = BUILD / PurePosixPath(old['archive']['key']).name
                if not kept.is_file() and any(PurePosixPath(f['path']).suffix in COMPRESSED for f in pack['files']):
                    # Not built here: the copy stage keeps, or the one the CDN serves (a stored zip comes out the same
                    # anywhere; a deflated one only from the same zlib).
                    try:
                        shutil.copyfile(cached_archive(previous, old, DEFAULT_CACHE), kept)
                    except (LayoutError, OSError, urllib.error.URLError) as missing:
                        print(f"! {pack['name']}: the published archive could not be fetched ({missing}); building it again "
                              f"may give it a new key", file=sys.stderr)
                if kept.is_file() and kept.stat().st_size == old['archive']['bytes'] and sha256_of(kept) == old['archive']['sha256']:
                    pack['archive'] = old['archive']
                    print(f"  {pack['name']}: unchanged, {len(pack['files'])} files, {pack['bytes'] / MB:.1f} MB")
                    continue
            archive = BUILD / f"{pack['name']}.zip"
            digest = build_archive([(e['path'], sources[e['path']]) for e in pack['files']], archive)
            key = f"{ARCHIVE_PREFIX}{pack['name']}-{digest[:12]}.zip"
            final = BUILD / PurePosixPath(key).name
            archive.replace(final)
            pack['archive'] = {'key': key, 'bytes': final.stat().st_size, 'sha256': digest}
            print(f"  {pack['name']}: {len(pack['files'])} files, {pack['bytes'] / MB:.1f} MB")

        layout = {'version': 1, 'cdn': args.cdn.rstrip('/') + '/', 'packs': packs}
        LAYOUT_JSON.write_text(json.dumps(layout, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
        write_manifest(assets)
        write_pack_modules(play_packs)
        print(f'✓ {len(packs)} packs, {sum(a.bytes for a in assets) / MB:.0f} MB. Archives in {BUILD.relative_to(REPO)}')
    finally:
        files.close()


